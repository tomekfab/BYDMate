package com.bydmate.app.agent

/** Why an assistant-proposed action was not run. Used by every stage of the action pipeline. */
enum class ActionRejection {
    MALFORMED, UNSUPPORTED_VERSION, STALE_CAPABILITIES, UNKNOWN_KIND, UNKNOWN_COMMAND, NOT_EXECUTABLE,
    MISSING_VALUE, VALUE_OUT_OF_RANGE, UNEXPECTED_FIELD, EMPTY_DESTINATION, DESTINATION_INVALID, NOT_CORRELATED,
    DUPLICATE_TURN, EXPIRED, RECOVERED_NOT_EXECUTED, CANCELLED, CONFIRM_DECLINED, CONFIRM_UNAVAILABLE, BLOCKED_BY_GATE,
    ALIAS_UNAVAILABLE, LEDGER_UNAVAILABLE,
}
